def iter_all_sequences():
    """Yield sequence IDs 000000 through 001472."""
    for i in range(1473):
        yield f"{i:06d}"


def sequence_output_dir(zod_root: Path, seq: str) -> Path:
    """Return {zod_root}/output/{seq}."""
    seq = normalize_sequence_id(seq)
    return Path(zod_root).expanduser().resolve() / "output" / seq


def default_autospeed_checkpoint(zod_root: Path) -> Path:
    """Return {zod_root}/models/autospeed.pt."""
    return (
        Path(zod_root).expanduser().resolve()
        / "models"
        / "autospeed.pt"
    )